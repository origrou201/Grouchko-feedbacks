-- ---------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------

-- Every feedback a client submits.
create table if not exists public.reviews (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  -- Random id generated by the client's browser; prevents double submissions.
  submission_id uuid not null unique,
  name          text not null check (char_length(name) between 1 and 80),
  -- Stored as 10 digits without a dash, e.g. 0501234567.
  phone         text check (phone ~ '^05[0-9]{8}$'),
  liked         text check (char_length(liked) <= 1000),
  to_change     text check (char_length(to_change) <= 1000),
  tags          text[] not null default '{}'
                check (tags <@ array['sides', 'top', 'beard', 'lineup', 'length', 'fade']::text[]),
  -- Paths of the photos inside the "review-photos" storage bucket.
  photo_paths   text[] not null default '{}' check (cardinality(photo_paths) <= 3),
  -- How the client reached the form: QR code at the shop, WhatsApp link, or directly.
  source        text not null default 'direct' check (source in ('qr', 'whatsapp', 'direct')),
  consent       boolean not null check (consent),
  is_read       boolean not null default false
);

create index if not exists reviews_created_at_idx on public.reviews (created_at desc);

-- The Supabase users who are allowed into the dashboard (just you).
create table if not exists public.admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- One row per accepted submission, used to limit submissions per IP address.
-- Only a salted hash of the IP is stored, never the IP itself.
create table if not exists public.rate_limits (
  id         bigint generated always as identity primary key,
  ip_hash    text not null,
  created_at timestamptz not null default now()
);

create index if not exists rate_limits_ip_hash_created_at_idx
  on public.rate_limits (ip_hash, created_at desc);
create index if not exists rate_limits_created_at_idx
  on public.rate_limits (created_at);


-- ---------------------------------------------------------------------
-- 2. Helper functions
-- ---------------------------------------------------------------------

-- True when the logged-in user is listed in public.admins.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;

-- Records a submission for this IP hash and returns false if the IP already
-- reached the limit inside the time window. Called only by the website server.
create or replace function public.check_rate_limit(
  p_ip_hash text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  recent_count integer;
begin
  -- Serialize concurrent requests from the same IP.
  perform pg_advisory_xact_lock(hashtext(p_ip_hash));

  -- Housekeeping: old rows are no longer needed.
  delete from public.rate_limits where created_at < now() - interval '1 day';

  select count(*) into recent_count
  from public.rate_limits
  where ip_hash = p_ip_hash
    and created_at > now() - make_interval(secs => p_window_seconds);

  if recent_count >= p_limit then
    return false;
  end if;

  insert into public.rate_limits (ip_hash) values (p_ip_hash);
  return true;
end;
$$;

-- Numbers for the top of the dashboard. Runs with the caller's permissions,
-- so row level security applies and only the admin gets real numbers.
create or replace function public.review_stats(p_time_zone text default 'Asia/Jerusalem')
returns json
language sql
stable
security invoker
set search_path = ''
as $$
  select json_build_object(
    'total', (select count(*) from public.reviews),
    'this_month', (
      select count(*) from public.reviews
      where created_at >= (date_trunc('month', now() at time zone p_time_zone) at time zone p_time_zone)
    ),
    'unread', (select count(*) from public.reviews where not is_read),
    'with_changes', (
      select count(*) from public.reviews where nullif(btrim(to_change), '') is not null
    ),
    'change_tags', coalesce((
      select json_agg(json_build_object('tag', t.tag, 'count', t.count) order by t.count desc, t.tag)
      from (
        select tag, count(*)::int as count
        from public.reviews, unnest(tags) as tag
        where nullif(btrim(to_change), '') is not null
        group by tag
      ) t
    ), '[]'::json)
  );
$$;


-- ---------------------------------------------------------------------
-- 3. Permissions and Row Level Security
--
-- Anonymous visitors get NO direct access to anything. Client submissions
-- go through the website's server, which checks the honeypot, the timing
-- and the rate limit before saving (using the secret key).
-- The logged-in admin can read reviews, mark them read/unread, and delete them.
-- ---------------------------------------------------------------------

alter table public.reviews     enable row level security;
alter table public.admins      enable row level security;
alter table public.rate_limits enable row level security;

revoke all on public.reviews, public.admins, public.rate_limits from anon, authenticated;
grant select, delete on public.reviews to authenticated;
grant update (is_read) on public.reviews to authenticated;
grant all on public.reviews, public.admins, public.rate_limits to service_role;

drop policy if exists "Admin can read reviews" on public.reviews;
create policy "Admin can read reviews" on public.reviews
  for select to authenticated
  using ((select public.is_admin()));

drop policy if exists "Admin can update reviews" on public.reviews;
create policy "Admin can update reviews" on public.reviews
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Admin can delete reviews" on public.reviews;
create policy "Admin can delete reviews" on public.reviews
  for delete to authenticated
  using ((select public.is_admin()));

-- admins and rate_limits have RLS on and no policies: nobody can read or
-- change them through the API (only the SQL editor and the server can).

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated, service_role;

revoke all on function public.check_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.check_rate_limit(text, integer, integer) to service_role;

revoke all on function public.review_stats(text) from public, anon;
grant execute on function public.review_stats(text) to authenticated, service_role;


-- ---------------------------------------------------------------------
-- 4. Storage: a PRIVATE bucket for review photos
--
-- Uploads happen through one-time signed upload links created by the
-- server, so no upload policy is needed. Only the admin can view
-- (through short-lived signed links) and delete photos.
-- ---------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('review-photos', 'review-photos', false, 3145728, array['image/jpeg', 'image/webp'])
on conflict (id) do update
  set public             = false,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Admin can view review photos" on storage.objects;
create policy "Admin can view review photos" on storage.objects
  for select to authenticated
  using (bucket_id = 'review-photos' and (select public.is_admin()));

drop policy if exists "Admin can delete review photos" on storage.objects;
create policy "Admin can delete review photos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'review-photos' and (select public.is_admin()));
